    @Test
    fun calculatorsAnswerAsOnTheJvm() {
        val expected = mapOf(
            "Road trip is 840 km. The rental uses 6.5 litres per 100 km and petrol is 1.89 euros a litre. If 3 of us split the fuel, how much does each person pay?" to "34.40 euros each",
            "I've got 2,000,000 Vietnamese dong left. The exchange office gives 25,400 dong per US dollar and takes a 3% commission. How many dollars do I get back?" to "76.38 US dollars",
            "3 of us are hiking and we won't reach any water until the end of day 2. If each person drinks 3.5 litres a day, how much water do we need to carry from the start, and how much will it weigh per person?" to "21 litres",
            "My flight leaves Singapore at 23:50 local time and takes 13 h 45 min to London. Singapore is UTC+8 and London is UTC+1 right now. What time is it in London when I land?" to "06:35",
            "When do I leave to arrive by 9:00 if the walk takes 25 minutes?" to "08:35",
            "A hostel is 18 euros a night. How much for 9 nights with a 10% discount?" to "145.80 euros",
            "What is 30 degrees Celsius in Fahrenheit?" to "86°F",
        )
        val wrong = expected.mapNotNull { (question, answer) ->
            val result = Calculators.solve(question)
            if (result?.complete == true && answer in result.text) null
            else question.take(40) + " => " + (result?.let { "complete=${it.complete} " + it.text.replace("\n", " ").take(160) } ?: "null")
        }
        if (wrong.isNotEmpty()) fail(wrong.joinToString("\n"))
    }
